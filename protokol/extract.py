"""Извлечение поручений из стенограммы локальной LLM.

Стенограмма может быть на русском, казахском или смешанной — поручение
одинаково валидно на любом из них:

  русский  «подготовьте претензию до десятого октября»
  казахский «жауапты — Ерлан Нұрланұлы, мерзімі — жиырма бесінші қазан»
  смешанный «тренингке смета дайындаңыз, к пятнице нужно»

Поэтому в подсказку явно заложены казахские месяцы и дни недели: без них
модель оставляет «жиырма бесінші қазан» как есть, и срок не превращается
в дату.
"""
import json
import llm

KZ_HINTS = """Казахские ориентиры для сроков:
  месяцы: қаңтар=январь, ақпан=февраль, наурыз=март, сәуір=апрель,
          мамыр=май, маусым=июнь, шілде=июль, тамыз=август,
          қыркүйек=сентябрь, қазан=октябрь, қараша=ноябрь, желтоқсан=декабрь
  числительные: он=10, жиырма=20, отыз=30; «жиырма бесінші»=25-е
  дни: дүйсенбі=пн, сейсенбі=вт, сәрсенбі=ср, бейсенбі=чт, жұма=пт
  «жұма күні»=в пятницу, «осы аптада»=на этой неделе,
  «апта соңына дейін»=до конца недели
  слова поручения: тапсырма=поручение, жауапты=ответственный,
  мерзімі=срок, дайындаңыз=подготовьте, жүргізіңіз=проведите,
  тексеріңіз=проверьте"""

SYSTEM = """Ты — секретарь совещания. Из стенограммы извлекаешь поручения.

Верни СТРОГО JSON, без markdown-обёртки:
{
 "participants": [{"name":"ФИО","role":"должность или null"}],
 "topics": ["тема 1","тема 2"],
 "tasks": [
   {"assignee":"ФИО ответственного",
    "task":"суть поручения в повелительном наклонении, ПО-РУССКИ",
    "due_raw":"срок дословно как прозвучал",
    "due_date":"YYYY-MM-DD или null",
    "lang":"ru|kk|mixed — на каком языке прозвучало поручение",
    "urgency":"высокая|средняя|низкая",
    "area":"направление: закуп|финансы|безопасность|кадры|юридическое|производство|прочее",
    "quote":"дословная цитата-основание из стенограммы"}
 ],
 "summary":"3-5 предложений по итогам"
}

Правила:
- Поручение = конкретное действие с исполнителем. Обсуждение — не поручение.
- Поручением считается и самообязательство: «я свяжусь с подрядчиком и до
  конца недели дам график», «мен подрядчикпен сөйлесемін, до конца недели
  график беремін». Ответственный здесь — тот, КТО ГОВОРИТ.
- due_raw — только выражение времени («до пятницы», «жиырма бесінші қазан»,
  «на этой неделе»). Если срок не назван — верни null, НЕ вставляй туда
  обрывок соседней фразы.
- Стенограмма может быть на нескольких языках. Поле "task" всегда по-русски,
  "quote" — на языке оригинала.
- Если реплики подписаны именами, ответственного бери из обращения, а не
  из того, кто говорит.
- due_date считай относительно даты совещания.
- urgency: «высокая» — если назван жёсткий срок в пределах недели, прозвучало
  «срочно», «немедленно», «не затягивайте», либо речь о происшествии или риске;
  «низкая» — если срок дальше месяца или не назван вовсе; иначе «средняя».
- quote — точный фрагмент из текста. Ничего не выдумывай.

""" + KZ_HINTS


import re, datetime

# слова, по которым выражение опознаётся как срок
TIME_WORDS = re.compile(
    r"\d|январ|феврал|март|апрел|ма[йя]|июн|июл|август|сентябр|октябр|ноябр|декабр"
    r"|қаңтар|ақпан|наурыз|сәуір|мамыр|маусым|шілде|тамыз|қыркүйек|қазан|қараша|желтоқсан"
    r"|недел|день|дня|дней|месяц|квартал|завтра|сегодня|срок|конц|начал"
    r"|понедельник|вторник|сред|четверг|пятниц|суббот|воскресен"
    r"|дүйсенбі|сейсенбі|сәрсенбі|бейсенбі|жұма|сенбі|жексенбі"
    r"|апта|күн|ай|мерзім|дейін|кейін|бүгін|ертең", re.I)


def _resolve_due(task: dict, meeting: str) -> dict:
    """Дату считаем правилами, модели оставляем только неохваченное.

    Приоритет у кода: он воспроизводим, а модель на одном и том же
    «до конца недели» в разных прогонах давала разные даты.
    """
    import datetime as _dt
    import dates
    try:
        base = _dt.date.fromisoformat(meeting)
    except ValueError:
        return task
    d = dates.resolve(task.get("due_raw") or "", base)
    if d is None:
        d = dates.resolve(task.get("quote") or "", base)
    if d is not None:
        task["due_date"] = d.isoformat()
        task["due_source"] = "правило"
    elif task.get("due_date"):
        task["due_source"] = "модель"
    return task


def _clean_due(task: dict) -> dict:
    """Срок должен быть сроком.

    LLM изредка кладёт в due_raw обрывок соседней фразы («тағы бір та»).
    В протоколе это выглядит как мусор, поэтому проверяем: если в строке
    нет ни одного признака времени — считаем, что срок не назван.
    Дату сверх горизонта совещания тоже отбрасываем.
    """
    raw = (task.get("due_raw") or "").strip()
    if raw and not TIME_WORDS.search(raw):
        task["due_raw"] = None
    d = task.get("due_date")
    if isinstance(d, str):
        try:
            datetime.date.fromisoformat(d)
        except ValueError:
            task["due_date"] = None
    if not task.get("due_raw") and not task.get("due_date"):
        task["due_raw"] = "не указан"
    return task


SWEEP = """Ты — контролёр протокола. Тебе дана стенограмма и список уже
найденных поручений. Найди ТОЛЬКО ТЕ, КОТОРЫХ В СПИСКЕ НЕТ.

Помни: поручение — это и самообязательство («я до пятницы дам график»,
«мен подрядчикпен сөйлесемін»), и просьба, адресованная конкретному
человеку, даже если слово «поручаю» не прозвучало.

Верни СТРОГО JSON того же формата, что и первый проход:
{"tasks": [{"assignee": "...", "task": "...", "due_raw": "...",
            "due_date": "...", "lang": "...", "quote": "..."}]}
Каждое поручение — ОБЪЕКТ, не строка. Имя ответственного кладётся
в поле assignee, а не приписывается к тексту поручения.
Если ничего не пропущено — верни {"tasks": []}.

""" + KZ_HINTS


def _key(t: dict) -> str:
    """ключ для склейки дубликатов между проходами"""
    import re as _re
    w = _re.findall(r"[а-яёәғқңөұүі]{4,}", (t.get("task") or "").lower())
    return " ".join(sorted(w)[:4]) + "|" + (t.get("assignee") or "").lower()[:12]


def run(transcript: str, meeting_date: str = "2026-09-22",
        weekday: str = "вторник", sweep: bool = True) -> dict:
    """Извлечение в два прохода.

    Один проход нестабилен: в двух запусках подряд модель нашла разные
    подмножества поручений — то «проверьте смету», то «согласуйте
    график». Для протокола пропуск поручения дороже лишней строки,
    поэтому вторым проходом спрашиваем, что осталось за кадром, и
    объединяем. Температура нулевая, чтобы результат воспроизводился.
    """
    user = (f"Дата совещания: {meeting_date} ({weekday}).\n\n"
            f"СТЕНОГРАММА:\n{transcript}\n\nJSON:")
    data = llm.generate_json(SYSTEM, user, max_tokens=3000, temp=0.0)
    tasks = [t for t in data.get("tasks", []) if t.get("task")]

    if sweep:
        found = "\n".join(f"- {t.get('assignee')}: {t.get('task')}" for t in tasks)
        u2 = (f"Дата совещания: {meeting_date} ({weekday}).\n\n"
              f"СТЕНОГРАММА:\n{transcript}\n\n"
              f"УЖЕ НАЙДЕНО:\n{found or '(пусто)'}\n\nJSON:")
        try:
            extra = llm.generate_json(SWEEP, u2, max_tokens=1500, temp=0.0)
        except Exception:
            extra = {"tasks": []}
        seen = {_key(t) for t in tasks}
        for t in extra.get("tasks", []):
            # второй проход иногда отдаёт строки вместо объектов —
            # формат подсказки для него мягче, и модель этим пользуется
            if isinstance(t, str):
                t = {"task": t, "assignee": None, "due_raw": None}
            if not isinstance(t, dict) or not t.get("task"):
                continue
            if _key(t) not in seen:
                seen.add(_key(t))
                tasks.append(t)

    data["tasks"] = [_clean_due(_resolve_due(t, meeting_date)) for t in tasks]
    return data


if __name__ == "__main__":
    import sys
    text = open(sys.argv[1]).read() if len(sys.argv) > 1 else sys.stdin.read()
    print(json.dumps(run(text), ensure_ascii=False, indent=1))
