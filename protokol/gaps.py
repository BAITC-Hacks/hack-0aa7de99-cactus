"""Детектор незакрытых решений.

Главная боль кейса — не в том, что поручение потерялось, а в том, что
его нельзя исполнить: прозвучало «надо подготовить», «вернёмся к этому
в пятницу», но кто и к какому сроку — не сказано.

Система на такой фразе обязана не выдумывать имя и дату, а показать
пробел и попросить человека его закрыть. Это принципиально: выдуманный
ответственный хуже отсутствующего — его не проверить.

Заодно размечаем, чем фраза является: обсуждением, предложением,
принятым решением или поручением. Так чужая мысль не попадёт в протокол
как утверждённое решение.

Модуль отдельный: работает поверх готовой стенограммы и ничего не знает
об извлечении поручений.
"""
import json
import llm

KIND = ["обсуждение", "предложение", "решение", "поручение"]

SYSTEM = """Ты — контролёр исполнительской дисциплины. Тебе дана стенограмма
совещания и список поручений, которые уже оформлены полностью.

Найди фразы, которые ЗВУЧАТ как намерение что-то сделать, но исполнить и
проконтролировать их нельзя, потому что не назван ответственный или срок.

Примеры таких фраз:
  «надо подготовить смету»            — не сказано кому
  «вернёмся к этому в пятницу»        — не сказано кто готовит
  «этот вопрос надо проработать»      — нет ни исполнителя, ни срока
  «мы должны усилить контроль»        — намерение без действия

Верни СТРОГО JSON:
{"gaps": [
  {"quote": "дословная фраза из стенограммы",
   "what": "о чём идёт речь, по-русски, одной строкой",
   "kind": "обсуждение|предложение|решение|поручение",
   "missing": ["ответственный"] или ["срок"] или ["ответственный","срок"],
   "who_hint": "кого можно назначить, если из контекста понятно, иначе null",
   "when_hint": "какой срок напрашивается, если из контекста понятно, иначе null"}
]}

Правила:
- НИКОГДА не выдумывай имя или дату. Если не названо — значит missing.
  who_hint и when_hint — это подсказка человеку, а не ответ; ставь их
  только когда в тексте есть прямое основание.
- Не дублируй то, что уже есть в списке оформленных поручений.
- Вежливые формулы («спасибо», «все свободны») пропусками не являются.
- kind: «обсуждение» — просто обмен мнениями; «предложение» — кто-то
  предложил, но не согласовано; «решение» — договорились, но исполнитель
  не назначен; «поручение» — адресовано человеку, но без срока.
- Если пробелов нет — верни {"gaps": []}."""


import re, difflib


def _words(s: str) -> list[str]:
    return re.findall(r"[а-яёәғқңөұүіa-z0-9]+", (s or "").lower())


def quote_is_real(quote: str, transcript: str, threshold: float = 0.8) -> bool:
    """Цитата обязана действительно звучать на записи.

    Модель охотно пересказывает своими словами: в замере из пяти цитат
    две («вернёмся к этому в пятницу», «проведите») в стенограмме не
    встречались. Пропускать такое нельзя — весь смысл модуля в том,
    чтобы не выдумывать. Сверяем нечётко: пунктуация и регистр могут
    отличаться, слова — нет.
    """
    q, t = _words(quote), _words(transcript)
    if len(q) < 1 or not t:
        return False
    sm = difflib.SequenceMatcher(None, q, t, autojunk=False)
    hit = sum(b.size for b in sm.get_matching_blocks())
    return hit / len(q) >= threshold


def _duplicates(text: str, tasks: list[dict], threshold: float = 0.3) -> bool:
    """пробел, совпадающий с уже оформленным поручением, не пробел"""
    a = set(_words(text))
    if not a:
        return False
    for t in tasks or []:
        b = set(_words(t.get("task")))
        if b and len(a & b) / len(a | b) >= threshold:
            return True
    return False


def find(transcript: str, tasks: list[dict] | None = None) -> list[dict]:
    done = "\n".join(f"- {t.get('assignee')}: {t.get('task')}"
                     for t in (tasks or []))
    user = (f"СТЕНОГРАММА:\n{transcript}\n\n"
            f"УЖЕ ОФОРМЛЕНО:\n{done or '(пусто)'}\n\nJSON:")
    try:
        data = llm.generate_json(SYSTEM, user, max_tokens=2000, temp=0.0)
    except Exception:
        return []
    out = []
    for g in data.get("gaps", []):
        if not isinstance(g, dict) or not g.get("quote"):
            continue
        miss = g.get("missing") or []
        if isinstance(miss, str):
            miss = [miss]
        miss = [m for m in miss if m in ("ответственный", "срок")]
        if not miss:
            continue                       # без пробела это не наш случай
        g["missing"] = miss
        if g.get("kind") not in KIND:
            g["kind"] = "обсуждение"
        # два обязательных фильтра, оба на стороне кода
        if not quote_is_real(g["quote"], transcript):
            continue                       # цитата пересказана — выбрасываем
        if _duplicates(g.get("what") or g["quote"], tasks or []):
            continue                       # это уже оформленное поручение
        out.append(g)
    return out


if __name__ == "__main__":
    import sys
    d = json.load(open(sys.argv[1]))
    for g in find(d["transcript"], d.get("tasks")):
        print(f"[{g['kind']}] нет: {', '.join(g['missing'])}")
        print(f"   {g['what']}")
        print(f"   «{g['quote'][:110]}»\n")
