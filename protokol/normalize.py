"""Восстановление пунктуации и заглавных букв в выводе казахской модели.

Дообученная казахская модель выдаёт сплошной нижний регистр без знаков
препинания: «жауапты ерлан нұрланұлы мерзімі жиырма бесінші қазан».
Для протокола это негодный вид.

Восстанавливаем локальной LLM — но с проверкой. Модель, которую просят
«расставить запятые», охотно заодно переписывает текст. Поэтому после
генерации сверяем состав слов с исходником: если совпадение ниже порога,
возвращаем исходный текст. Лучше без запятых, чем с выдумкой.
"""
import re, difflib

PROMPT = """Расставь в тексте знаки препинания и заглавные буквы.

ЗАПРЕЩЕНО: менять слова, добавлять слова, удалять слова, переводить,
исправлять ошибки, менять порядок слов.
РАЗРЕШЕНО: только знаки препинания, регистр букв и границы предложений.

Текст может быть на казахском, русском или смешанным — сохраняй язык
каждого слова как есть.

Верни ТОЛЬКО обработанный текст, без пояснений."""


def _words(s: str) -> list[str]:
    return re.findall(r"\w+", s.lower())


def fidelity(src: str, out: str) -> float:
    """доля слов исходника, уцелевших в результате"""
    a, b = _words(src), _words(out)
    if not a:
        return 1.0
    return difflib.SequenceMatcher(None, a, b, autojunk=False).ratio()


def restore(text: str, generate_fn, min_fidelity: float = 0.93) -> tuple[str, float]:
    """generate_fn(system, user) -> str. Возвращает (текст, точность).

    При точности ниже порога возвращаем исходный текст: расстановка
    пунктуации не стоит риска подмены слов в протоколе.
    """
    text = text.strip()
    if not text:
        return text, 1.0
    try:
        out = generate_fn(PROMPT, text).strip()
    except Exception:
        return text, 0.0
    out = re.sub(r"^```\w*|```$", "", out).strip()
    f = fidelity(text, out)
    return (out, f) if f >= min_fidelity else (text, f)
