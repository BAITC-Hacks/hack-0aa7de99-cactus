"""Разбор сроков из живой речи в абсолютные даты — кодом, не моделью.

LLM справляется с «до 15 октября», но плавает на относительных сроках:
в двух прогонах подряд «до конца недели» превратилось то в 2026-10-10,
то в null. Для протокола, где по сроку ставят контроль исполнения, такой
разброс недопустим, поэтому дату считаем детерминированно, а модель
оставляем только для случаев, которые правила не покрывают.

Поддерживаются русские и казахские формулировки.
"""
import re, datetime

MONTHS = {
    "январ": 1, "феврал": 2, "март": 3, "апрел": 4, "ма[йя]": 5, "июн": 6,
    "июл": 7, "август": 8, "сентябр": 9, "октябр": 10, "ноябр": 11, "декабр": 12,
    "қаңтар": 1, "ақпан": 2, "наурыз": 3, "сәуір": 4, "мамыр": 5, "маусым": 6,
    "шілде": 7, "тамыз": 8, "қыркүйек": 9, "қазан": 10, "қараша": 11,
    "желтоқсан": 12,
}

WEEKDAYS = {
    "понедельник": 0, "вторник": 1, "сред": 2, "четверг": 3, "пятниц": 4,
    "суббот": 5, "воскресен": 6,
    "дүйсенбі": 0, "сейсенбі": 1, "сәрсенбі": 2, "бейсенбі": 3, "жұма": 4,
    "сенбі": 5, "жексенбі": 6,
}

# Числительные прописью: порядковые (по основе) и количественные (по слову
# целиком). Разделение важно: основа «дв» иначе съедала бы «двадцать».
NUMERALS = {
    # порядковые — сопоставляются по основе
    r"одиннадцат\w*": 11, r"двенадцат\w*": 12, r"тринадцат\w*": 13,
    r"четырнадцат\w*": 14, r"пятнадцат\w*": 15, r"шестнадцат\w*": 16,
    r"семнадцат\w*": 17, r"восемнадцат\w*": 18, r"девятнадцат\w*": 19,
    r"двадцат\w*": 20, r"тридцат\w*": 30,
    r"перв\w*": 1, r"втор\w*": 2, r"трет\w*": 3, r"четверт\w*": 4,
    r"пят\w*": 5, r"шест\w*": 6, r"седьм\w*": 7, r"восьм\w*": 8,
    r"девят\w*": 9, r"десят\w*": 10,
    # количественные — только целым словом
    r"\bодну\b|\bодной\b|\bодного\b": 1,
    r"\bдве\b|\bдвух\b|\bдвум\b": 2,
    r"\bтри\b|\bтрёх\b|\bтрех\b": 3,
    r"\bчетыре\b|\bчетырёх\b": 4,
    # казахские порядковые и количественные
    r"бірінші": 1, r"екінші": 2, r"үшінші": 3, r"төртінші": 4, r"бесінші": 5,
    r"алтыншы": 6, r"жетінші": 7, r"сегізінші": 8, r"тоғызыншы": 9,
    r"оныншы": 10, r"жиырма": 20, r"отыз": 30, r"\bон\b": 10,
    r"\bекі\b": 2, r"\bүш\b": 3, r"\bтөрт\b": 4, r"\bбес\b": 5,
}


def _numeral(text: str) -> int | None:
    """«жиырма бесінші» = 20 + 5 = 25; «двадцать пятого» = 25.

    Длинные шаблоны проверяются первыми и вырезаются из строки, иначе
    «двадцать» разобралось бы как «два».
    """
    total, found = 0, False
    for key, val in sorted(NUMERALS.items(), key=lambda kv: -len(kv[0])):
        if re.search(key, text, re.I):
            total += val
            found = True
            text = re.sub(key, " ", text, flags=re.I)
    return total if found and 1 <= total <= 31 else None


def resolve(raw: str, meeting: datetime.date) -> datetime.date | None:
    """Строка срока → дата. None, если правила не покрывают случай."""
    if not raw:
        return None
    s = raw.lower().strip()

    # 1) «до 15 октября», «25-ші қазан», «жиырма бесінші қазан»
    for pat, mon in MONTHS.items():
        if re.search(pat, s):
            m = re.search(r"(\d{1,2})", s)
            day = int(m.group(1)) if m else _numeral(s)
            if day and 1 <= day <= 31:
                year = meeting.year + (1 if mon < meeting.month - 6 else 0)
                try:
                    return datetime.date(year, mon, day)
                except ValueError:
                    return None

    # 2) «через две недели», «за две недели», «екі апта»
    m = re.search(r"(\d+)\s*(недел|апта)", s)
    n = int(m.group(1)) if m else None
    if n is None and re.search(r"недел|апта", s):
        n = _numeral(s)
    if n and re.search(r"недел|апта", s) and not re.search(r"конц|соң|этой|осы", s):
        return meeting + datetime.timedelta(weeks=n)

    # 3) «до конца недели», «апта соңына дейін», «на этой неделе»
    if re.search(r"конц\w*\s+недел|апта\s+соң|на этой недел|осы апта|текущ\w*\s+недел", s):
        return meeting + datetime.timedelta(days=(4 - meeting.weekday()) % 7)

    # 4) «на следующей неделе», «келесі аптада»
    if re.search(r"следующ\w*\s+недел|келесі апта", s):
        return meeting + datetime.timedelta(days=(7 - meeting.weekday()) % 7 or 7)

    # 5) день недели: «к пятнице», «жұма күні»
    for key, wd in WEEKDAYS.items():
        if re.search(key, s):
            delta = (wd - meeting.weekday()) % 7
            return meeting + datetime.timedelta(days=delta or 7)

    # 6) «завтра», «ертең», «сегодня», «бүгін»
    if re.search(r"завтра|ертең", s):
        return meeting + datetime.timedelta(days=1)
    if re.search(r"сегодня|бүгін", s):
        return meeting

    # 7) «через 3 дня», «через три дня», «екі күн»
    if re.search(r"\bдн\w*|\bдень\b|\bкүн\w*", s):
        m = re.search(r"(\d+)\s*(?:дн|день|дней|күн)", s)
        n = int(m.group(1)) if m else _numeral(s)
        if n and 1 <= n <= 90:
            return meeting + datetime.timedelta(days=n)
    return None


if __name__ == "__main__":
    d = datetime.date(2026, 9, 22)          # вторник
    cases = [
        ("до десятого октября", "2026-10-10"),
        ("до 15 октября", "2026-10-15"),
        ("жиырма бесінші қазан", "2026-10-25"),
        ("25-ші қазан", "2026-10-25"),
        ("до конца недели", "2026-09-25"),
        ("апта соңына дейін", "2026-09-25"),
        ("к пятнице", "2026-09-25"),
        ("жұма күні", "2026-09-25"),
        ("за две недели", "2026-10-06"),
        ("на следующей неделе", "2026-09-28"),
        ("завтра", "2026-09-23"),
        ("ертең", "2026-09-23"),
        ("на этой неделе", "2026-09-25"),
        ("не указан", None),
        ("через три дня", "2026-09-25"),
        ("екі апта", "2026-10-06"),
        ("до 30 сентября", "2026-09-30"),
        ("к 20 октября", "2026-10-20"),
        ("до двадцать пятого октября", "2026-10-25"),
        ("после совещания", None),
        ("тағы бір та", None),
    ]
    ok = 0
    for raw, want in cases:
        got = resolve(raw, d)
        got_s = got.isoformat() if got else None
        mark = "✅" if got_s == want else "❌"
        ok += got_s == want
        print(f"  {mark} {raw!r:<26} → {got_s}  (ожидалось {want})")
    print(f"\n{ok} из {len(cases)}")
